package dev.portfolio.designpattern.decorator.message;

/**
 * 데코레이터 패턴 복습 문제: 알림 메시지 꾸미기.
 *
 * <p>문제: 기본 메시지에 알림 문구를 붙이거나 대괄호를 씌우는 기능을 만든다.
 * 기능을 여러 번 조합할 수 있어야 하며, 적용 순서에 따라 결과가 달라져야 한다.</p>
 *
 * <p>만들어야 할 타입:</p>
 * <ul>
 *     <li>{@code Message}: {@code String getText()}를 선언하는 인터페이스.</li>
 *     <li>{@code PlainMessage}: 생성자로 받은 원문을 그대로 반환하는 기본 메시지.</li>
 *     <li>{@code PrefixDecorator}: 전달받은 메시지의 결과 앞에 {@code "알림: "}를 붙인다.</li>
 *     <li>{@code BracketDecorator}: 전달받은 메시지의 결과 전체를 {@code "["}와
 *         {@code "]"}로 감싼다.</li>
 * </ul>
 *
 * <p>요구사항:</p>
 * <ul>
 *     <li>세 클래스는 모두 {@code Message} 인터페이스를 구현한다.</li>
 *     <li>{@code PlainMessage}는 생성자로 {@code String text}를 받아 보관한다.</li>
 *     <li>두 데코레이터는 생성자로 기존 {@code Message} 객체를 받아 보관한다.</li>
 *     <li>데코레이터의 {@code getText()}는 보관한 객체의 {@code getText()} 결과에
 *         자기 기능을 적용하여 반환한다.</li>
 *     <li>다른 데코레이터뿐 아니라 같은 데코레이터도 여러 번 적용할 수 있어야 한다.</li>
 *     <li>원본 메시지는 변경하지 않는다. 같은 객체의 메서드를 반복 호출해도 결과는 같다.</li>
 * </ul>
 *
 * <p>입출력 예시: 원문이 {@code "안녕하세요"}일 때 아래 결과를 반환한다.
 * 적용 순서는 기본 메시지를 시작으로 새 데코레이터를 바깥에 감싸는 순서이다.</p>
 * <ul>
 *     <li>기본 메시지 → {@code "안녕하세요"}</li>
 *     <li>알림 문구 추가 → {@code "알림: 안녕하세요"}</li>
 *     <li>대괄호 추가 → {@code "[안녕하세요]"}</li>
 *     <li>알림 문구 추가 후 대괄호 추가 → {@code "[알림: 안녕하세요]"}</li>
 *     <li>대괄호 추가 후 알림 문구 추가 → {@code "알림: [안녕하세요]"}</li>
 *     <li>대괄호 두 번 추가 → {@code "[[안녕하세요]]"}</li>
 * </ul>
 *
 * <p>제한 조건:</p>
 * <ul>
 *     <li>원문과 데코레이터에 전달하는 객체는 null이 아니다.</li>
 *     <li>원문은 빈 문자열일 수 있으며, 원문에 포함된 공백은 그대로 유지한다.</li>
 *     <li>알림 문구는 콜론 뒤 공백 한 칸을 포함한 {@code "알림: "}로 고정한다.</li>
 *     <li>대괄호 안팎에는 별도의 공백을 추가하지 않는다.</li>
 * </ul>
 *
 * <p>테스트 목표: 위 여섯 예시, 빈 원문, 반복 호출 시 같은 결과,
 * 장식 후에도 원본 객체의 결과가 유지되는지 JUnit으로 확인한다.</p>
 */
public interface Message {

    String getText();
}
